SET NOCOUNT ON;
SET XACT_ABORT ON;

DECLARE @CONFIRMAR_RESET BIT = 1;

IF @CONFIRMAR_RESET <> 1
    THROW 51100, 'Reset cancelado: confirme explicitamente a operacao.', 1;

IF DB_NAME() <> 'DB_COPILOT_ACME'
    THROW 51101, 'Reset cancelado: banco diferente de DB_COPILOT_ACME.', 1;

IF OBJECT_ID('dbo.TB_TODOS', 'U') IS NULL
    THROW 51102, 'Reset cancelado: tabela dbo.TB_TODOS nao encontrada.', 1;

BEGIN TRY
    BEGIN TRANSACTION;

    DECLARE @RESET_EM DATETIME2(0) = SYSDATETIME();
    DECLARE @ARQUIVADAS TABLE (ID_TODO INT NOT NULL PRIMARY KEY);

    UPDATE dbo.TB_TODOS
    SET
        ARQUIVADA = 1,
        DATA_ATUALIZACAO = @RESET_EM
    OUTPUT INSERTED.ID_TODO INTO @ARQUIVADAS (ID_TODO)
    WHERE ISNULL(ARQUIVADA, 0) = 0;

    COMMIT TRANSACTION;

    SELECT
        @RESET_EM AS RESET_EM,
        COUNT(1) AS TAREFAS_ARQUIVADAS
    FROM @ARQUIVADAS;

    SELECT ID_TODO
    FROM @ARQUIVADAS
    ORDER BY ID_TODO;
END TRY
BEGIN CATCH
    IF @@TRANCOUNT > 0
        ROLLBACK TRANSACTION;
    THROW;
END CATCH;
