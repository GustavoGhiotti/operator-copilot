/*
    Personalizacao da Aurora na Arena.

    Regras de economia:
    - XP_TOTAL apenas desbloqueia visuais e nunca e debitado.
    - Aurora Coins continuam na carteira oficial do Album.
    - A compra registra o gasto no extrato album.TB_ALBUM_AURORA_COIN_MOVIMENTACAO.

    Banco esperado: DB_COPILOT_ACME
*/

SET NOCOUNT ON;
SET XACT_ABORT ON;

IF DB_NAME() <> 'DB_COPILOT_ACME'
    THROW 51201, 'Migration cancelada: banco diferente de DB_COPILOT_ACME.', 1;

IF OBJECT_ID('album.TB_ALBUM_AURORA_COIN_SALDO', 'U') IS NULL
    THROW 51202, 'Carteira de Aurora Coins nao encontrada.', 1;

IF OBJECT_ID('album.TB_ALBUM_AURORA_COIN_MOVIMENTACAO', 'U') IS NULL
    THROW 51203, 'Extrato de Aurora Coins nao encontrado.', 1;

BEGIN TRANSACTION;

IF OBJECT_ID('dbo.TB_ARENA_AURORA_ITEM', 'U') IS NULL
BEGIN
    CREATE TABLE dbo.TB_ARENA_AURORA_ITEM (
        ID_ITEM INT IDENTITY(1, 1) NOT NULL
            CONSTRAINT PK_TB_ARENA_AURORA_ITEM PRIMARY KEY,
        CODIGO VARCHAR(60) NOT NULL,
        NOME NVARCHAR(100) NOT NULL,
        DESCRICAO NVARCHAR(300) NULL,
        SLOT VARCHAR(20) NOT NULL,
        RARIDADE VARCHAR(20) NOT NULL
            CONSTRAINT DF_TB_ARENA_AURORA_ITEM_RARIDADE DEFAULT ('COMUM'),
        PRECO_COINS INT NOT NULL
            CONSTRAINT DF_TB_ARENA_AURORA_ITEM_PRECO DEFAULT (0),
        XP_NECESSARIO INT NOT NULL
            CONSTRAINT DF_TB_ARENA_AURORA_ITEM_XP DEFAULT (0),
        CHAVE_VISUAL VARCHAR(80) NOT NULL,
        ORDEM INT NOT NULL
            CONSTRAINT DF_TB_ARENA_AURORA_ITEM_ORDEM DEFAULT (0),
        ATIVO BIT NOT NULL
            CONSTRAINT DF_TB_ARENA_AURORA_ITEM_ATIVO DEFAULT (1),
        DT_CRIACAO DATETIME2(0) NOT NULL
            CONSTRAINT DF_TB_ARENA_AURORA_ITEM_CRIACAO DEFAULT (SYSDATETIME()),
        DT_ATUALIZACAO DATETIME2(0) NOT NULL
            CONSTRAINT DF_TB_ARENA_AURORA_ITEM_ATUALIZACAO DEFAULT (SYSDATETIME()),
        CONSTRAINT UQ_TB_ARENA_AURORA_ITEM_CODIGO UNIQUE (CODIGO),
        CONSTRAINT CK_TB_ARENA_AURORA_ITEM_SLOT CHECK (
            SLOT IN ('CABECA', 'OCULOS', 'BRINCO', 'MAQUIAGEM', 'SUPERIOR', 'INFERIOR', 'CALCADO')
        ),
        CONSTRAINT CK_TB_ARENA_AURORA_ITEM_PRECO CHECK (PRECO_COINS >= 0),
        CONSTRAINT CK_TB_ARENA_AURORA_ITEM_XP CHECK (XP_NECESSARIO >= 0)
    );
END;

IF OBJECT_ID('dbo.TB_ARENA_AURORA_INVENTARIO', 'U') IS NULL
BEGIN
    CREATE TABLE dbo.TB_ARENA_AURORA_INVENTARIO (
        CPF_COLABORADOR VARCHAR(20) NOT NULL,
        ID_ITEM INT NOT NULL,
        PRECO_PAGO_COINS INT NOT NULL,
        ID_MOVIMENTACAO_AURORA UNIQUEIDENTIFIER NULL,
        DT_AQUISICAO DATETIME2(0) NOT NULL
            CONSTRAINT DF_TB_ARENA_AURORA_INV_AQUISICAO DEFAULT (SYSDATETIME()),
        CONSTRAINT PK_TB_ARENA_AURORA_INVENTARIO
            PRIMARY KEY (CPF_COLABORADOR, ID_ITEM),
        CONSTRAINT FK_TB_ARENA_AURORA_INV_ITEM
            FOREIGN KEY (ID_ITEM)
            REFERENCES dbo.TB_ARENA_AURORA_ITEM (ID_ITEM),
        CONSTRAINT CK_TB_ARENA_AURORA_INV_PRECO CHECK (PRECO_PAGO_COINS >= 0)
    );

    CREATE INDEX IX_TB_ARENA_AURORA_INV_ITEM
        ON dbo.TB_ARENA_AURORA_INVENTARIO (ID_ITEM, CPF_COLABORADOR);
END;

IF OBJECT_ID('dbo.TB_ARENA_AURORA_EQUIPADO', 'U') IS NULL
BEGIN
    CREATE TABLE dbo.TB_ARENA_AURORA_EQUIPADO (
        CPF_COLABORADOR VARCHAR(20) NOT NULL,
        SLOT VARCHAR(20) NOT NULL,
        ID_ITEM INT NOT NULL,
        DT_EQUIPADO DATETIME2(0) NOT NULL
            CONSTRAINT DF_TB_ARENA_AURORA_EQ_DATA DEFAULT (SYSDATETIME()),
        CONSTRAINT PK_TB_ARENA_AURORA_EQUIPADO
            PRIMARY KEY (CPF_COLABORADOR, SLOT),
        CONSTRAINT FK_TB_ARENA_AURORA_EQ_ITEM
            FOREIGN KEY (ID_ITEM)
            REFERENCES dbo.TB_ARENA_AURORA_ITEM (ID_ITEM),
        CONSTRAINT CK_TB_ARENA_AURORA_EQ_SLOT CHECK (
            SLOT IN ('CABECA', 'OCULOS', 'BRINCO', 'SUPERIOR', 'INFERIOR', 'CALCADO')
        )
    );

    CREATE UNIQUE INDEX UX_TB_ARENA_AURORA_EQ_ITEM_SLOT
        ON dbo.TB_ARENA_AURORA_EQUIPADO (CPF_COLABORADOR, ID_ITEM);
END;

MERGE dbo.TB_ARENA_AURORA_ITEM AS DESTINO
USING (VALUES
    ('OCULOS_PULSE', N'Oculos Pulse', N'Armacao ciano com brilho holografico.', 'OCULOS', 'COMUM', 100, 100, 'oculos-pulse', 10),
    ('OCULOS_SOLAR_ORBITA', N'Oculos Orbita', N'Lentes solares com acabamento laranja.', 'OCULOS', 'EPICO', 320, 1000, 'oculos-solar-orbita', 20),
    ('BONE_ARENA', N'Bone Arena', N'Bone oficial com detalhes laranja e ciano.', 'CABECA', 'COMUM', 160, 250, 'bone-arena', 30),
    ('FONE_NEON', N'Fone Neon', N'Headset futurista para quem chegou longe na Arena.', 'CABECA', 'LENDARIO', 480, 1500, 'fone-neon', 40),
    ('BRINCO_ORBITA', N'Brinco Orbita', N'Par de brincos luminosos em forma de orbita.', 'BRINCO', 'RARO', 120, 300, 'brinco-orbita', 50),
    ('JAQUETA_LUNAR', N'Jaqueta Lunar', N'Jaqueta clara com recortes holograficos.', 'SUPERIOR', 'RARO', 350, 500, 'jaqueta-lunar', 60),
    ('MOLETOM_COSMOS', N'Moletom Cosmos', N'Moletom azul profundo com pulso ciano.', 'SUPERIOR', 'EPICO', 450, 1000, 'moletom-cosmos', 70),
    ('CALCA_CARGO_CIANO', N'Calca Cargo Ciano', N'Cargo azul-marinho com bolsos luminosos.', 'INFERIOR', 'RARO', 260, 500, 'calca-cargo-ciano', 80),
    ('CALCA_PULSE_ORANGE', N'Calca Pulse', N'Calca esportiva com faixa laranja lateral.', 'INFERIOR', 'EPICO', 380, 1000, 'calca-pulse-orange', 90),
    ('TENIS_PULSE', N'Tenis Pulse', N'Tenis branco com solado de energia ciano.', 'CALCADO', 'COMUM', 220, 250, 'tenis-pulse', 100),
    ('SANDALIA_HOLO', N'Sandalia Holo', N'Sandalia leve com tiras holograficas.', 'CALCADO', 'RARO', 180, 750, 'sandalia-holo', 110)
) AS ORIGEM (
    CODIGO, NOME, DESCRICAO, SLOT, RARIDADE,
    PRECO_COINS, XP_NECESSARIO, CHAVE_VISUAL, ORDEM
)
ON DESTINO.CODIGO = ORIGEM.CODIGO
WHEN MATCHED THEN UPDATE SET
    NOME = ORIGEM.NOME,
    DESCRICAO = ORIGEM.DESCRICAO,
    SLOT = ORIGEM.SLOT,
    RARIDADE = ORIGEM.RARIDADE,
    PRECO_COINS = ORIGEM.PRECO_COINS,
    XP_NECESSARIO = ORIGEM.XP_NECESSARIO,
    CHAVE_VISUAL = ORIGEM.CHAVE_VISUAL,
    ORDEM = ORIGEM.ORDEM,
    ATIVO = 1,
    DT_ATUALIZACAO = SYSDATETIME()
WHEN NOT MATCHED THEN INSERT (
    CODIGO, NOME, DESCRICAO, SLOT, RARIDADE,
    PRECO_COINS, XP_NECESSARIO, CHAVE_VISUAL, ORDEM, ATIVO
) VALUES (
    ORIGEM.CODIGO, ORIGEM.NOME, ORIGEM.DESCRICAO, ORIGEM.SLOT,
    ORIGEM.RARIDADE, ORIGEM.PRECO_COINS, ORIGEM.XP_NECESSARIO,
    ORIGEM.CHAVE_VISUAL, ORIGEM.ORDEM, 1
);

COMMIT TRANSACTION;

SELECT
    COUNT(*) AS ITENS_ATIVOS,
    MIN(XP_NECESSARIO) AS MENOR_XP,
    MAX(XP_NECESSARIO) AS MAIOR_XP
FROM dbo.TB_ARENA_AURORA_ITEM
WHERE ATIVO = 1;
